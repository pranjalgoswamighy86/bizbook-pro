/**
 * v4.152: IRP (Invoice Registration Portal) Integration Library
 * ============================================================
 * Direct integration with the Indian GST IRP for e-invoice generation.
 *
 * Flow:
 *   1. Tenant configures GSP (GST Suvidha Provider) credentials in Settings
 *   2. We authenticate with IRP via the GSP and receive a bearer token (valid 60 min)
 *   3. For each B2B invoice, we generate the INV-01 JSON payload (already implemented)
 *   4. We sign the payload with the tenant's digital signature (optional — IRP accepts unsigned for GSP route)
 *   5. POST to /einvoice/api/v1/einvoice (IRP API) → returns IRN + AckNo + AckDate + SignedQR
 *   6. Persist these fields on the Sale record
 *
 * Environment variables:
 *   - IRP_GSP_CODE: GSP identifier (e.g. 'clear', 'adaequare', ' Mastersindia')
 *   - IRP_GSP_USERNAME: GSP-issued username
 *   - IRP_GSP_PASSWORD: GSP-issued password
 *   - IRP_GSP_CLIENT_ID: GSP-issued client ID
 *   - IRP_GSP_CLIENT_SECRET: GSP-issued client secret
 *   - IRP_ENV: 'sandbox' or 'production' (default: sandbox)
 *
 * Sandbox URL: https://einvoice1.traces.gov.in
 * Production URL: https://einvoice.gst.gov.in
 *
 * If GSP credentials are not configured, the API returns MANUAL mode — user copies
 * the INV-01 JSON, submits it manually to the IRP portal, then pastes back IRN/AckNo.
 *
 * References:
 *   - https://einvoice1.traces.gov.in/IrpFileDownload/Web/HelpMultipage.htm
 *   - IRN cancellation window: 24 hours from generation
 *   - IRN format: 64-character hex string
 */

import crypto from 'crypto'
import { isValidIrpSuccessResult } from './gsp-response-policy'

const IRP_SANDBOX_URL = 'https://einvoice1.traces.gov.in'
const IRP_PRODUCTION_URL = 'https://einvoice.gst.gov.in'

import type { TenantGspConfig } from './gsp-credentials'

export function getIrpBaseUrl(config: TenantGspConfig): string {
  return config.irpEnv === 'production' ? IRP_PRODUCTION_URL : IRP_SANDBOX_URL
}

export function isIrpConfigured(config: TenantGspConfig | null): boolean {
  return !!(config && config.tenantId && config.gspCode && config.gspClientId &&
    config.gspClientSecret && config.gspUsername && config.gspPassword)
}

interface GspAuthResponse {
  access_token: string
  token_type: string
  expires_in: number
  scope: string
}

const tokenCache = new Map<string, { token: string; expiresAt: number; fingerprint: string }>()

function credentialFingerprint(config: TenantGspConfig): string {
  return crypto.createHash('sha256').update([
    config.gspCode, config.gspClientId, config.gspClientSecret,
    config.gspUsername, config.gspPassword, config.irpEnv,
  ].join('\\0')).digest('hex')
}

async function getIrpAuthToken(config: TenantGspConfig): Promise<string> {
  const fingerprint = credentialFingerprint(config)
  const cached = tokenCache.get(config.tenantId)
  if (cached && cached.fingerprint === fingerprint && Date.now() < cached.expiresAt - 5 * 60 * 1000) {
    return cached.token
  }

  const baseUrl = getIrpBaseUrl(config)
  const authRes = await fetch(`${baseUrl}/ein-v1/registration/authenticate`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'gsp-code': config.gspCode },
    body: JSON.stringify({
      Username: config.gspUsername,
      Password: config.gspPassword,
      ClientId: config.gspClientId,
      ClientSecret: config.gspClientSecret,
      GrantType: 'password',
    }),
    signal: AbortSignal.timeout(15000),
  })
  if (!authRes.ok) throw new Error(`GSP authentication failed (HTTP ${authRes.status}).`)
  const authData: GspAuthResponse = await authRes.json()
  if (!authData.access_token || !Number.isFinite(authData.expires_in) || authData.expires_in <= 0) {
    throw new Error('GSP authentication returned an invalid token response.')
  }
  tokenCache.set(config.tenantId, {
    token: authData.access_token,
    expiresAt: Date.now() + authData.expires_in * 1000,
    fingerprint,
  })
  return authData.access_token
}

export interface IrpSubmitResult {
  success: boolean
  irn?: string
  ackNo?: string
  ackDate?: string
  signedQrCode?: string
  errorMessage?: string
  mode: 'LIVE' | 'MANUAL'
}

/**
 * Submit an INV-01 payload to IRP for IRN generation.
 *
 * @param inv01Payload — the JSON payload generated by /api/einvoice generate-payload
 * @returns IrpSubmitResult with IRN + AckNo on success, or MANUAL mode flag
 */
export async function submitToIrp(inv01Payload: any, config: TenantGspConfig | null): Promise<IrpSubmitResult> {
  // If GSP not configured, return MANUAL mode
  if (!config || !isIrpConfigured(config)) {
    return {
      success: false,
      mode: 'MANUAL',
      errorMessage: 'IRP not configured. Submit the INV-01 payload manually to the IRP portal, then paste back IRN/AckNo.',
    }
  }

  try {
    const token = await getIrpAuthToken(config)
    const baseUrl = getIrpBaseUrl(config)

    const res = await fetch(`${baseUrl}/einvoice/api/v1/einvoice`, {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${token}`,
        'Content-Type': 'application/json',
        'gsp-code': config.gspCode,
      },
      body: JSON.stringify(inv01Payload),
      signal: AbortSignal.timeout(20000),
    })

    if (!res.ok) {
      const errText = `HTTP ${res.status}`
      return {
        success: false,
        mode: 'LIVE',
        errorMessage: `IRP HTTP ${res.status}: ${errText.slice(0, 500)}`,
      }
    }

    const data = await res.json()

    // IRP success response shape:
    // {
    //   "Message": "IRN generated successfully",
    //   "Status": 1,
    //   "Result": {
    //     "AckNo": 123456789012345,
    //     "AckDt": "2024-01-15 14:30:00",
    //     "Irn": "abc123...xyz (64 hex chars)",
    //     "SignedInvoice": "...",
    //     "SignedQRCode": "..."
    //   },
    //   "Info": [...]
    // }
    if (data.Status === 1 || data.Status === '1') {
      if (!isValidIrpSuccessResult(data.Result)) {
        return { success: false, mode: 'LIVE', errorMessage: 'IRP returned success without a valid 64-character IRN and acknowledgement details.' }
      }
      return {
        success: true,
        mode: 'LIVE',
        irn: data.Result.Irn.toUpperCase(),
        ackNo: String(data.Result.AckNo),
        ackDate: data.Result.AckDt,
        signedQrCode: data.Result.SignedQRCode,
      }
    }

    // IRP returned an error (Status 0)
    const errorMessages = (data.ErrorDetails || []).map((e: any) => e.ErrorMessage).join('; ')
    return {
      success: false,
      mode: 'LIVE',
      errorMessage: errorMessages || data.Message || 'Unknown IRP error',
    }
  } catch (err: any) {
    return {
      success: false,
      mode: 'LIVE',
      errorMessage: `Network error: ${err?.message || 'Unknown'}`,
    }
  }
}

/**
 * Cancel an existing IRN on IRP.
 * Allowed within 24 hours of generation.
 * @param irn — the 64-char IRN to cancel
 * @param reason — reason code (1-6 per IRP spec)
 */
export async function cancelIrn(irn: string, reason: string, config: TenantGspConfig | null): Promise<IrpSubmitResult> {
  if (!config || !isIrpConfigured(config)) {
    return {
      success: false,
      mode: 'MANUAL',
      errorMessage: 'IRP not configured. Cancel the IRN manually on the IRP portal.',
    }
  }

  try {
    const token = await getIrpAuthToken(config)
    const baseUrl = getIrpBaseUrl(config)

    const res = await fetch(`${baseUrl}/einvoice/api/v1/einvoice/cancel`, {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${token}`,
        'Content-Type': 'application/json',
        'gsp-code': config.gspCode,
      },
      body: JSON.stringify({ Irn: irn, CnlRsn: reason, CnlRem: 'Cancelled via BizBook Pro' }),
      signal: AbortSignal.timeout(20000),
    })

    if (!res.ok) {
      const errText = `HTTP ${res.status}`
      return {
        success: false,
        mode: 'LIVE',
        errorMessage: `IRP cancel HTTP ${res.status}: ${errText.slice(0, 500)}`,
      }
    }

    const data = await res.json()
    if (data.Status === 1 || data.Status === '1') {
      return { success: true, mode: 'LIVE' }
    }

    const errorMessages = (data.ErrorDetails || []).map((e: any) => e.ErrorMessage).join('; ')
    return {
      success: false,
      mode: 'LIVE',
      errorMessage: errorMessages || 'IRN cancellation failed',
    }
  } catch (err: any) {
    return {
      success: false,
      mode: 'LIVE',
      errorMessage: `Network error: ${err?.message || 'Unknown'}`,
    }
  }
}

/**
 * Get IRN details from IRP (e.g. to verify a pasted-back IRN is real).
 */
export async function getIrnDetails(irn: string, config: TenantGspConfig | null): Promise<IrpSubmitResult & { data?: any }> {
  if (typeof irn !== 'string' || !/^[A-Fa-f0-9]{64}$/.test(irn.trim())) {
    return { success: false, mode: 'LIVE', errorMessage: 'A valid 64-character IRN is required.' }
  }
  if (!config || !isIrpConfigured(config)) {
    return {
      success: false,
      mode: 'MANUAL',
      errorMessage: 'IRP not configured.',
    }
  }

  try {
    const token = await getIrpAuthToken(config)
    const baseUrl = getIrpBaseUrl(config)

    const res = await fetch(`${baseUrl}/einvoice/api/v1/einvoice/irn/${encodeURIComponent(irn.trim().toUpperCase())}`, {
      method: 'GET',
      headers: {
        'Authorization': `Bearer ${token}`,
        'gsp-code': config.gspCode,
      },
      signal: AbortSignal.timeout(20000),
    })

    if (!res.ok) {
      return {
        success: false,
        mode: 'LIVE',
        errorMessage: `IRP get HTTP ${res.status}`,
      }
    }

    const data = await res.json()
    const success = data.Status === 1 || data.Status === '1'
    if (success && !isValidIrpSuccessResult(data.Result)) {
      return { success: false, mode: 'LIVE', errorMessage: 'IRP returned an incomplete IRN lookup response.' }
    }
    return {
      success,
      mode: 'LIVE',
      irn: success ? data.Result.Irn.toUpperCase() : undefined,
      ackNo: success ? String(data.Result.AckNo) : undefined,
      ackDate: success ? data.Result.AckDt : undefined,
      signedQrCode: success ? data.Result.SignedQRCode : undefined,
      data: data.Result,
    }
  } catch (err: any) {
    return {
      success: false,
      mode: 'LIVE',
      errorMessage: `Network error: ${err?.message || 'Unknown'}`,
    }
  }
}

